#!/usr/bin/env node
/**
 * Build script to inject environment variables into miniprogram config
 * Usage: node scripts/build-miniprogram-config.mjs
 * 
 * Required environment variables:
 * - NEXT_PUBLIC_APP_ORIGIN: API base URL
 * - WECHAT_MINIPROGRAM_APP_ID: WeChat miniprogram AppID
 */

import { writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const rootDir = join(__dirname, '..');
const configPath = join(rootDir, 'miniprogram', 'config.ts');

// Read environment variables (required, no defaults)
const apiBaseUrl = process.env.NEXT_PUBLIC_APP_ORIGIN;
const appId = process.env.WECHAT_MINIPROGRAM_APP_ID;

// Validate required environment variables
if (!apiBaseUrl) {
  console.error('❌ Error: NEXT_PUBLIC_APP_ORIGIN environment variable is required');
  process.exit(1);
}

if (!appId) {
  console.error('❌ Error: WECHAT_MINIPROGRAM_APP_ID environment variable is required');
  process.exit(1);
}

// Generate config file content
const configContent = `/**
 * Miniprogram configuration
 * Auto-generated by build script - DO NOT EDIT MANUALLY
 * Generated at: ${new Date().toISOString()}
 */

export const CONFIG = {
  // API base URL (from NEXT_PUBLIC_APP_ORIGIN)
  API_BASE_URL: '${apiBaseUrl}',
  
  // App ID (from WECHAT_MINIPROGRAM_APP_ID)
  APP_ID: '${appId}',
} as const;
`;

// Write config file
writeFileSync(configPath, configContent, 'utf-8');
console.log('✅ Miniprogram config generated:');
console.log(`   API_BASE_URL: ${apiBaseUrl}`);
console.log(`   APP_ID: ${appId}`);

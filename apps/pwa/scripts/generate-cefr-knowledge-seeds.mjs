#!/usr/bin/env node
/**
 * Generates sharded SQL seeds from apps/pwa/data/cefr-*.json into supabase/seeds/08-cefr-vocab-part-*.sql
 * Run from repo: node apps/pwa/scripts/generate-cefr-knowledge-seeds.mjs
 *
 * Requires migration 20260329110000 (UNIQUE name, level, pos) and 20260329120000 (example_sentence, image_name; no metadata).
 */

import {
  writeFileSync,
  mkdirSync,
  readdirSync,
  unlinkSync,
  readFileSync,
} from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const pwaRoot = join(__dirname, '..');

const DATA_FILES = [
  'cefr-a1.json',
  'cefr-a2.json',
  'cefr-b1.json',
  'cefr-b2.json',
  'cefr-c1.json',
  'cefr-c2.json',
];

/** Rows per file — keep each shard small for git and tooling */
const ROWS_PER_SHARD = 200;

const seedsDir = join(pwaRoot, 'supabase', 'seeds');
const dataDir = join(pwaRoot, 'data');

function escapeSqlString(s) {
  return String(s).replace(/\\/g, '\\\\').replace(/'/g, "''");
}

function buildValuesRow(row) {
  const name = escapeSqlString(row.englishWord);
  const description = escapeSqlString(row.chineseTranslation ?? '');
  const pos = escapeSqlString(row.pos ?? '');
  const level = escapeSqlString(row.level ?? '');
  const prompt = escapeSqlString(row.selfExaminePrompt ?? '');
  const theme = escapeSqlString(row.theme ?? '');
  const exampleSentence = escapeSqlString(row.exampleSentence ?? '');
  const imagePart =
    row.imageName == null || row.imageName === ''
      ? 'NULL'
      : `'${escapeSqlString(String(row.imageName))}'`;
  return `('', '${name}', '${description}', '${pos}', '${level}', '${prompt}', '${theme}', false, '${exampleSentence}', ${imagePart})`;
}

function main() {
  mkdirSync(seedsDir, { recursive: true });

  for (const f of readdirSync(seedsDir)) {
    if (/^08-cefr-vocab-part-\d+\.sql$/.test(f)) {
      unlinkSync(join(seedsDir, f));
    }
  }

  const allRows = [];
  for (const file of DATA_FILES) {
    const raw = JSON.parse(readFileSync(join(dataDir, file), 'utf8'));
    if (!Array.isArray(raw)) {
      throw new Error(`${file}: expected array`);
    }
    for (const row of raw) {
      allRows.push(row);
    }
  }

  let part = 1;
  for (let i = 0; i < allRows.length; i += ROWS_PER_SHARD) {
    const chunk = allRows.slice(i, i + ROWS_PER_SHARD);
    const values = chunk.map(buildValuesRow).join(',\n');

    const sql = `-- CEFR vocabulary (part ${part}, rows ${chunk.length}) — generated by scripts/generate-cefr-knowledge-seeds.mjs
SET search_path TO public;

INSERT INTO public.knowledge (code, name, description, pos, level, self_examine_prompt, theme, needs_correction, example_sentence, image_name)
VALUES
${values}
ON CONFLICT (name, level, pos) DO NOTHING;
`;

    const outName = `08-cefr-vocab-part-${String(part).padStart(3, '0')}.sql`;
    writeFileSync(join(seedsDir, outName), sql, 'utf-8');
    console.log(`Wrote ${outName} (${chunk.length} rows)`);
    part += 1;
  }

  console.log(`\nDone: ${part - 1} shard(s), ${allRows.length} total rows.`);
}

main();
